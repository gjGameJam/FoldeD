{
    [Header("Constants")]
    private const float ACCELERATION_OF_GRAVITY = 9.81f; //  m/s^2
    private const float DENSITY_OF_AIR = 1.225f; //  kg/m^3 at sea level 15 degrees C
    private const float DYNAMIC_VISCOSITY_OF_AIR = .0000181f; //kg/ms at sea level 15 degrees C
    private const float BLASIUS_LAMINAR_DRAG_COEFFICIENT = 1.328f;

    [Header("Script and object refs")]
    private GeneSequence geneSeq; //gene sequence containing representations for glider creation
    private PaperAirplanePhysicsAttributes physNums;
    private Rigidbody rb; //rigid body for glider to perform torque on
    //TODO: add a mesh collider and use the mesh generated by triangleMeshGenerator
    private GeneManger geneManager;//ref to gene manager to save upon crash

    //fields and callback to communicate fitness with gene manager via game manager callback
    private float startingFitness;
